/// The country of `callsign` as VarAC names it: the longest prefix of the call without
/// its last character that is in the table; None when nothing matches.
pub fn country_of(callsign: &str) -> Option<&'static str> {
    let call = callsign.trim().to_uppercase();
    let n = call.chars().count();
    (1..n).rev().find_map(|i| {
        let p: String = call.chars().take(i).collect();
        PREFIXES.binary_search_by(|(k, _)| (*k).cmp(p.as_str())).ok().map(|j| PREFIXES[j].1)
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn countries_like_varac() {
        assert!(PREFIXES.windows(2).all(|w| w[0].0 < w[1].0));
        assert_eq!(country_of("W1ABC"), Some("United States of America"));
        assert_eq!(country_of("KH6XYZ"), Some("Hawaii"));
        assert_eq!(country_of("DL1ABC"), Some("Federal Republic of Germany"));
        assert_eq!(country_of("OK1AB"), Some("Czech Republic"));
        assert_eq!(country_of("OM3AB"), Some("Slovak Republic"));
        assert_eq!(country_of(""), None);
    }
}
